/* A valid question mark used if an internal glyph is malformed or empty. */
static const uint8_t s_fallback_question[FONT_W] = { 2u, 1u, 81u, 9u, 6u };

/* Built lazily.  The atomic flag keeps the first-call race well-defined. */
static uint8_t s_bits[FONT_COUNT][FONT_W];
static _Atomic unsigned char s_built;

/* Count at most FONT_W characters and require a terminating NUL at index 5. */
static int row_has_width(const char *row)
{
    int n = 0;
    while (n <= FONT_W && row[n] != '\0') {
        ++n;
    }
    return n == FONT_W && row[FONT_W] == '\0';
}

/* Build one glyph, returning 1 when it contained at least one lit pixel. */
static int build_glyph(unsigned int g)
{
    unsigned int r;
    unsigned int c;
    int lit = 0;

    for (c = 0u; c < FONT_W; ++c) {
        s_bits[g][c] = 0u;
    }
    for (r = 0u; r < FONT_H; ++r) {
        const char *row = GLYPH_ART[g][r];
        if (!row_has_width(row)) {
            continue; /* never read past a malformed row */
        }
        for (c = 0u; c < FONT_W; ++c) {
            if (row[c] == '#') {
                s_bits[g][c] = (uint8_t)(s_bits[g][c] | (uint8_t)(1u << r));
                lit = 1;
            }
        }
    }
    return lit;
}

const uint8_t *font5x7_glyph(int ch)
{
    unsigned int g;

    if (ch < FONT_FIRST || ch > FONT_LAST) {
        ch = '?';
    }
    g = (unsigned int)(ch - FONT_FIRST);

    if (s_built == 0u) {
        unsigned int i;
        for (i = 0u; i < FONT_COUNT; ++i) {
            if (!build_glyph(i)) {
                unsigned int c;
                for (c = 0u; c < FONT_W; ++c) {
                    s_bits[i][c] = s_fallback_question[c];
                }
            }
        }
        s_built = 1u;
    }
    return s_bits[g];
}
